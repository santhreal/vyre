//! Generated catalog of machine-readable codes this crate emits.
//!
//! [`ErrorCode`] classifies a backend dispatch failure and carries a stable u32
//! a consumer can filter on without parsing message text. The catalog renders
//! from `ErrorCode::ALL`, so a row changes only when the code that produces it
//! changes.

use super::ErrorCode;

/// Render the catalog as TOML.
///
/// The committed copy at `docs/generated/driver-error-codes.toml` is compared
/// against this on every test run.
#[must_use]
pub fn render_catalog_toml() -> String {
    let mut out = String::with_capacity(4096);
    out.push_str("# Generated by vyre-runtime. Do not edit by hand.\n");
    out.push_str("# Regenerate: ./cargo_full run -p xtask --bin xtask -- error-codes --write\n");
    out.push_str("#\n");
    out.push_str("# Integer ids are append-only: an existing assignment is never reused or\n");
    out.push_str("# renumbered, because consumers persist them in telemetry and alert rules.\n");

    for code in ErrorCode::ALL {
        out.push_str("\n[[backend_error]]\n");
        out.push_str(&format!("variant = {:?}\n", format!("{code:?}")));
        out.push_str(&format!("id = {}\n", code.stable_id()));
        out.push_str(&format!("summary = {:?}\n", code.summary()));
    }

    out
}
